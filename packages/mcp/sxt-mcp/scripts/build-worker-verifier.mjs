#!/usr/bin/env node
/**
 * Builds a Cloudflare Workers-loadable copy of the SDK's proof verifier.
 *
 * sxt-proof-of-sql-sdk ships its WASM as a base64 string inside index.js and
 * compiles it at load time with WebAssembly.instantiate(bytes). Workers forbid
 * compiling WebAssembly from bytes at runtime; a module must be imported. This
 * script performs a mechanical transform of the pinned SDK file:
 *
 *   1. Decode the embedded base64 into worker-gen/sxt-verifier.wasm.
 *   2. Copy the JS glue to worker-gen/sxt-verifier.mjs, replacing only the two
 *      lines that decode and instantiate the bytes with an import of the .wasm
 *      module and WebAssembly.instantiate(module, imports).
 *
 * Nothing else in the SDK changes. The input is pinned by version AND sha256,
 * so an SDK upgrade fails this build until someone re-reviews the transform
 * (and lib/prover.ts, which mirrors the SDK's request sequence).
 *
 * Output is generated, gitignored, and rebuilt by `npm run build:worker`.
 */

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PINNED_VERSION = "0.54.0";
const PINNED_SHA256 = "4cf3b359fb11ce51474d1a9686c99d709aa9f6ec02fbbb251e1b937b4ea0a193";

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG = resolve(HERE, "..");
const SDK = resolve(PKG, "node_modules", "sxt-proof-of-sql-sdk");
const OUT = resolve(PKG, "worker-gen");

const meta = JSON.parse(await readFile(resolve(SDK, "package.json"), "utf8"));
if (meta.version !== PINNED_VERSION) {
  throw new Error(`sxt-proof-of-sql-sdk is ${meta.version}; this transform is pinned to ${PINNED_VERSION}.`);
}
const source = await readFile(resolve(SDK, "index.js"), "utf8");
const sha = createHash("sha256").update(source).digest("hex");
if (sha !== PINNED_SHA256) {
  throw new Error(`sxt-proof-of-sql-sdk index.js sha256 ${sha} does not match the pinned ${PINNED_SHA256}.`);
}

const start = source.indexOf("let wasmCode = `");
const end = source.indexOf("`;", start);
if (start < 0 || end < 0) throw new Error("embedded wasmCode literal not found");
const b64 = source.slice(start + "let wasmCode = `".length, end).replace(/\s+/g, "");
const wasm = Buffer.from(b64, "base64");
if (wasm.subarray(0, 4).toString("latin1") !== "\0asm") throw new Error("decoded bytes are not a WASM module");

const DECODE = "const wasmBytes = Uint8Array.from(atob(wasmCode), c => c.charCodeAt(0));";
const INSTANTIATE = "const wasmInstance = (await WebAssembly.instantiate(wasmBytes, imports)).instance;";
for (const line of [DECODE, INSTANTIATE]) {
  if (source.split(line).length !== 2) throw new Error(`expected exactly one occurrence of: ${line}`);
}

const glue =
  "// GENERATED by scripts/build-worker-verifier.mjs from sxt-proof-of-sql-sdk " +
  `${PINNED_VERSION} (sha256 ${PINNED_SHA256}). Do not edit.\n` +
  'import wasmModule from "./sxt-verifier.wasm";\n' +
  source
    .slice(0, start)
    .concat(source.slice(end + 2))
    .replace(DECODE, "")
    .replace(INSTANTIATE, "const wasmInstance = await WebAssembly.instantiate(wasmModule, imports);");

await mkdir(OUT, { recursive: true });
await writeFile(resolve(OUT, "sxt-verifier.wasm"), wasm);
await writeFile(resolve(OUT, "sxt-verifier.mjs"), glue);
console.log(`[build-worker-verifier] wasm ${(wasm.length / 1024).toFixed(0)} KiB, glue ${(glue.length / 1024).toFixed(0)} KiB → worker-gen/`);
